"""Compatibility exports for the authored tutor provider.

Tutor content is no longer generated by an AI model. New code should import
from ``authored_content`` directly; these aliases keep older internal imports
and persisted-content tooling working during the migration.
"""

from .authored_content import (
    AUTHORED_CONTENT_VERSION,
    AuthoredContentUnavailable,
    authored_tutor_content,
)
from dataclasses import asdict
from copy import deepcopy
from ..models import GeneratedLessonContent
from .lesson_code import fixed_code_experiments, fixed_lesson_code

TUTOR_PROMPT_VERSION = AUTHORED_CONTENT_VERSION
TutorGenerationUnavailable = AuthoredContentUnavailable
generate_tutor_content = authored_tutor_content

# Minimal schema compatibility for older structure tests. It describes the
# authored six-section contract; it is not used for model validation or calls.
TUTOR_SCHEMA = {"properties": {"lesson": {"properties": {
    "sections": {"minItems": 6, "maxItems": 6, "items": {"properties": {
        "type": {"enum": ["meaning", "analogy", "example", "code", "result", "why_it_matters"]}
    }}},
    "code_explanation": {}, "key_takeaway": {},
}, "required": ["title", "introduction", "sections", "code_explanation", "key_takeaway"]}}}


def _lesson_with_fixed_code(lesson: dict | GeneratedLessonContent, task: str, stage: str) -> GeneratedLessonContent:
    payload = deepcopy(lesson.model_dump(mode="json") if isinstance(lesson, GeneratedLessonContent) else lesson)
    canonical = fixed_lesson_code(task, stage)
    for section in payload["sections"]:
        if section["type"] == "code":
            section["code"] = canonical.code
            section["language"] = canonical.language
    payload["try_this"] = [asdict(item) for item in fixed_code_experiments(task, stage)]
    return GeneratedLessonContent.model_validate(payload)
